namespace
{
	constexpr float PlaneMeshSize = 100.f; // /Engine/BasicShapes/Plane is 100x100
	constexpr float AimKind = 4.f;        // M_Tile kinds (Shaders/DI_Tile.hlsl)
	constexpr float RippleKind = 5.f;
	constexpr float LayerCenter = 2.f, LayerRing = 1.f, LayerDying = 0.5f, LayerRipple = 0.7f, LayerAim = 0.8f; // translucency order
	constexpr float GoldenRatioFrac = 0.6180339887f; // spreads ids into unlike stone seeds
	constexpr float AimClearCentre = 18.f, AimClearTile = 12.f; // gaps before the centre piece and a target tile
	// Settle tolerances: below these nothing visibly moves (~1 px), so Tick can stop.
	constexpr float SettleAngle = 0.003f, SettleAngleVel = 0.03f, SettleLength = 0.8f, SettleLengthVel = 6.f, SettleAlpha = 0.01f;
	constexpr float ShakeStop = 0.1f, FadeGone = 0.02f;
	constexpr float RippleStartTiles = 0.9f; // a ripple starts just inside its tile's edge
	constexpr float TileQuadPad = 1.25f; // stone quads are this much larger than the stone, room to squash and wobble (Shaders/DI_Tile.hlsl QuadPad)

	const UDIGameSettings& Feel() { return UDIGameSettings::Get(); }
}

void ADIRingActor::SetAim(float Angle, bool bAtTile)
{
	AimAngle = Angle; // snaps: the guide must answer the finger immediately
	bAimAtTile = bAtTile;
	AimTargetAlpha = 1.f;
	bAnimating = true;
	PushInstances();
}

void ADIRingActor::ClearAim()
{
	if (AimTargetAlpha > 0.f)
	{
		AimTargetAlpha = 0.f;
		bAnimating = true;
	}
}

ADIRingActor::ADIRingActor()
{
	PrimaryActorTick.bCanEverTick = true;

	static ConstructorHelpers::FObjectFinder<UStaticMesh> Plane(TEXT("/Engine/BasicShapes/Plane.Plane"));

	Background = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("Background"));
	RootComponent = Background;
	Background->SetStaticMesh(Plane.Object);
	Background->SetRelativeLocation(FVector(0, 0, -50));
	Background->SetRelativeScale3D(FVector(60.f));
	Background->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	Background->CastShadow = false;

	Tiles = CreateDefaultSubobject<UInstancedStaticMeshComponent>(TEXT("Tiles"));
	Tiles->SetupAttachment(RootComponent);
	Tiles->SetStaticMesh(Plane.Object);
	Tiles->SetAbsolute(true, true, true);
	Tiles->NumCustomDataFloats = 5;
	Tiles->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	Tiles->CastShadow = false;
}

void ADIRingActor::BeginPlay()
{
	Super::BeginPlay();

	// Generated by -run=DIGenerateAssets; loaded here (not in the constructor) so the commandlet can run before they exist.
	Background->SetMaterial(0, LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/DoubleIt/Materials/M_Background.M_Background")));
	Tiles->SetMaterial(0, LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/DoubleIt/Materials/M_Tile.M_Tile")));
}

void ADIRingActor::SetDark(bool bDark)
{
	Background->SetCustomPrimitiveDataFloat(1, bDark ? 1.f : 0.f);
	bLightTheme = !bDark;
	PushInstances();
}

void ADIRingActor::SyncFromGame(const FDIGame& Game, float Offset)
{
	ShowBoard(Game.GetRing(), Game.IsGameOver() ? nullptr : &Game.GetCenter(), Offset, nullptr, Game.GetMode());
}

void ADIRingActor::Impact(float Angle, float Strength, bool bReveal)
{
	FRipple& R = Ripples.AddDefaulted_GetRef();
	R.Pos = FVector2D(DIRingLayout::RingRadius * FMath::Sin(Angle), DIRingLayout::RingRadius * FMath::Cos(Angle));
	R.MaxSize = DIRingLayout::TileSize * (bReveal ? Feel().RevealRippleSize : FMath::Lerp(Feel().RippleSizeMin, Feel().RippleSizeMax, Strength));
	R.bReveal = bReveal;
	if (Strength > Feel().ShakeFrom)
	{
		ShakeAmp = FMath::Max(ShakeAmp, FMath::Lerp(Feel().ShakePixelsMin, Feel().ShakePixelsMax,
			(Strength - Feel().ShakeFrom) / FMath::Max(1.f - Feel().ShakeFrom, 1e-3f))); // felt, not seen
	}
	bAnimating = true;
}

void ADIRingActor::ShowBoard(const TArray<FDIPiece>& Ring, const FDIPiece* Center, float Offset, const FDIFusionEvent* Event, const FDIMode& InMode)
{
	Mode = InMode;

	struct FTarget
	{
		FDIPiece Piece;
		float Angle;
		float Radius;
		float Size;
		bool bCenter;
	};
	TMap<uint32, FTarget> Targets;
	if (Center)
	{
		Targets.Add(Center->Id, { *Center, 0.f, 0.f, DIRingLayout::CenterSize, true });
	}
	for (int32 i = 0; i < Ring.Num(); ++i)
	{
		Targets.Add(Ring[i].Id, { Ring[i], DIRingLayout::TileAngle(i, Ring.Num(), Offset), DIRingLayout::RingRadius, DIRingLayout::TileSize, false });
	}

	TMap<uint32, uint32> ConsumedBy;
	TSet<uint32> Results;
	if (Event)
	{
		Results.Add(Event->ResultId);
		for (uint32 Id : Event->ConsumedIds)
		{
			ConsumedBy.Add(Id, Event->ResultId);
		}
	}
	auto FinalTarget = [&](uint32 Id) -> const FTarget*
	{
		for (int32 Hop = 0; Hop < 32; ++Hop)
		{
			if (const FTarget* T = Targets.Find(Id))
			{
				return T;
			}
			const uint32* Next = ConsumedBy.Find(Id);
			if (!Next)
			{
				return nullptr;
			}
			Id = *Next;
		}
		return nullptr;
	};

	TSet<uint32> Seen;
	for (FTileVisual& V : Visuals)
	{
		if (const FTarget* T = Targets.Find(V.Piece.Id))
		{
			V.Piece = T->Piece;
			if (T->bCenter)
			{
				V.TargetAngle = V.Angle; // lifted pieces travel straight in along their own spoke
			}
			else
			{
				if (V.Radius < 1.f)
				{
					V.Angle = T->Angle; // placed pieces travel straight out along the target spoke
				}
				V.TargetAngle = T->Angle;
			}
			V.TargetRadius = T->Radius;
			V.TargetSize = T->Size;
			V.bCenter = T->bCenter;
			V.bDying = false;
			V.TargetAlpha = 1.f;
			Seen.Add(V.Piece.Id);
		}
		else if (!V.bDying)
		{
			V.bDying = true;
			V.bCenter = false;
			V.TargetAlpha = 0.f;
			V.TargetSize *= Feel().ConsumedShrink;
			if (ConsumedBy.Contains(V.Piece.Id))
			{
				if (const FTarget* Into = FinalTarget(V.Piece.Id))
				{
					// Merging pieces slide along the ring into the result.
					V.TargetAngle = Into->Angle;
					V.TargetRadius = Into->Radius;
				}
			}
		}
	}

	for (const TPair<uint32, FTarget>& Pair : Targets)
	{
		if (Seen.Contains(Pair.Key))
		{
			continue;
		}
		const FTarget& T = Pair.Value;
		FTileVisual& V = Visuals.AddDefaulted_GetRef();
		V.Piece = T.Piece;
		V.Angle = V.TargetAngle = T.Angle;
		V.Radius = V.TargetRadius = T.Radius;
		V.TargetSize = T.Size;
		V.bCenter = T.bCenter;
		V.Size = Results.Contains(Pair.Key) ? T.Size * Feel().PulseScale : 0.f;
		V.Seed = FMath::Frac(Pair.Key * GoldenRatioFrac);
	}

	Background->SetCustomPrimitiveDataFloat(0, float(Ring.Num()) / FMath::Max(Mode.Config.MaxRingPieces, 1));
	bAnimating = true;
	PushInstances();
}

void ADIRingActor::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);
	if (!bAnimating)
	{
		return; // idle breathing and shape drift run in M_Tile on the GPU; nothing to do here
	}

	const float Fade = 1.f - FMath::Exp(-Feel().FadeRate * DeltaSeconds);
	const float K = Feel().SpringStiffness;
	const float C = Feel().SpringDamping;
	const float H = FMath::Min(DeltaSeconds, 1.f / 30.f) / Feel().SpringSubsteps;
	bAnimating = false;
	for (FTileVisual& V : Visuals)
	{
		// Under-damped springs: a slight overshoot and settle reads as physical, a pure ease reads as software.
		for (int32 s = 0; s < Feel().SpringSubsteps; ++s)
		{
			V.AngleVel += (K * FMath::FindDeltaAngleRadians(V.Angle, V.TargetAngle) - C * V.AngleVel) * H; // shortest way round
			V.Angle += V.AngleVel * H;
			V.RadiusVel += (K * (V.TargetRadius - V.Radius) - C * V.RadiusVel) * H;
			V.Radius += V.RadiusVel * H;
			V.SizeVel += (K * (V.TargetSize - V.Size) - C * V.SizeVel) * H;
			V.Size = FMath::Max(V.Size + V.SizeVel * H, 0.f);
		}
		V.Alpha = FMath::Lerp(V.Alpha, V.TargetAlpha, Fade);
		bAnimating |= FMath::Abs(FMath::FindDeltaAngleRadians(V.Angle, V.TargetAngle)) > SettleAngle || FMath::Abs(V.AngleVel) > SettleAngleVel
			|| !FMath::IsNearlyEqual(V.Radius, V.TargetRadius, SettleLength) || FMath::Abs(V.RadiusVel) > SettleLengthVel
			|| !FMath::IsNearlyEqual(V.Size, V.TargetSize, SettleLength) || FMath::Abs(V.SizeVel) > SettleLengthVel
			|| !FMath::IsNearlyEqual(V.Alpha, V.TargetAlpha, SettleAlpha);
	}
	AimAlpha = FMath::Lerp(AimAlpha, AimTargetAlpha, 1.f - FMath::Exp(-14.f * DeltaSeconds));
	bAnimating |= !FMath::IsNearlyEqual(AimAlpha, AimTargetAlpha, SettleAlpha);

	for (FRipple& R : Ripples)
	{
		R.Age += DeltaSeconds;
	}
	Ripples.RemoveAll([](const FRipple& R) { return R.Age >= Feel().RippleSeconds; });
	ShakeAmp *= FMath::Exp(-14.f * DeltaSeconds);
	ShakeOffset = ShakeAmp > ShakeStop ? FVector2D(FMath::FRandRange(-1.f, 1.f), FMath::FRandRange(-1.f, 1.f)) * ShakeAmp : FVector2D::ZeroVector;
	bAnimating |= Ripples.Num() > 0 || ShakeAmp > ShakeStop;
	Visuals.RemoveAll([](const FTileVisual& V) { return V.bDying && V.Alpha < FadeGone; });
	PushInstances();
}

void ADIRingActor::PushInstances()
{
	// One instance list for tiles, impact ripples and aim dots; each carries [value, kind, rank, alpha, seed] for M_Tile.
	TArray<FTransform> Transforms;
	TArray<FVector4f> Data;
	TArray<float> Seeds;
	auto Add = [&](const FVector2D& Pos, float Z, float Size, const FVector4f& Custom, float Seed = 0.f)
	{
		Transforms.Emplace(FQuat::Identity, ToWorld(Pos + ShakeOffset, Z), FVector(FMath::Max(Size, 0.01f) / PlaneMeshSize));
		Data.Add(Custom);
		Seeds.Add(Seed);
	};

	for (const FTileVisual& V : Visuals)
	{
		// Centre above ring above dying pieces, so translucency sorts predictably.
		const float Z = V.bCenter ? LayerCenter : (V.bDying ? LayerDying : LayerRing);
		const FDIPiece& P = V.Piece;
		float Rank = 0.f;
		if (P.IsNumber() && Mode.IsValid())
		{
			Rank = float(Mode.Rules->ColourRank(P.Value));
		}
		Add(FVector2D(V.Radius * FMath::Sin(V.Angle), V.Radius * FMath::Cos(V.Angle)), Z, V.Size * TileQuadPad,
			FVector4f(float(FMath::Min<int64>(P.Value, 999999)), float(uint8(P.Kind)), Rank, V.Alpha), V.Seed);
	}

	for (const FRipple& R : Ripples)
	{
		const float T = R.Age / Feel().RippleSeconds;
		const float Ease = 1.f - FMath::Square(1.f - T);
		Add(R.Pos, LayerRipple, FMath::Lerp(DIRingLayout::TileSize * RippleStartTiles, R.MaxSize, Ease),
			FVector4f(R.bReveal ? 1.f : 0.f, RippleKind, bLightTheme ? 1.f : 0.f, Feel().RippleOpacity * FMath::Square(1.f - T)));
	}

	// Aim guide: dots along the spoke from the centre piece out to the gap (or the tile a minus would lift).
	if (AimAlpha > SettleAlpha)
	{
		const FVector2D Dir(FMath::Sin(AimAngle), FMath::Cos(AimAngle));
		const float Start = DIRingLayout::CenterSize * 0.5f + AimClearCentre;
		const float End = bAimAtTile ? DIRingLayout::RingRadius - DIRingLayout::TileSize * 0.5f - AimClearTile : DIRingLayout::RingRadius;
		const int32 Dots = FMath::Max(2, FMath::FloorToInt32((End - Start) / Feel().AimDotSpacing) + 1);
		for (int32 d = 0; d < Dots; ++d)
		{
			const float T = float(d) / (Dots - 1);
			const bool bTip = !bAimAtTile && d == Dots - 1; // a slightly larger dot marks the landing gap
			Add(Dir * FMath::Lerp(Start, End, T), LayerAim, bTip ? Feel().AimDotSize * Feel().AimTipScale : Feel().AimDotSize,
				FVector4f(bAimAtTile ? 1.f : 0.f, AimKind, bLightTheme ? 1.f : 0.f, AimAlpha * FMath::Lerp(Feel().AimOpacityNear, Feel().AimOpacityFar, T)));
		}
	}

	if (Tiles->GetInstanceCount() != Transforms.Num())
	{
		Tiles->ClearInstances();
		Tiles->AddInstances(Transforms, false);
	}
	else
	{
		Tiles->BatchUpdateInstancesTransforms(0, Transforms, false, false, true);
	}
	for (int32 i = 0; i < Data.Num(); ++i)
	{
		Tiles->SetCustomData(i, { Data[i].X, Data[i].Y, Data[i].Z, Data[i].W, Seeds[i] }, false);
	}
	Tiles->MarkRenderStateDirty();
}
